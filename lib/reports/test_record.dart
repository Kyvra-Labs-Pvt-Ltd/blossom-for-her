import 'dart:convert';
import 'dart:typed_data';

/// A captured test is an image record until assay calibration is implemented.
/// Demo indices are never treated as hormone concentrations.
class TestRecord {
  static const hormones = ['E3G', 'LH', 'PdG', 'FSH'];
  final String id;
  final DateTime capturedAt;
  final int cycleDay;
  final bool isDemo;
  final String? readerName;
  final String? selectedChannel;
  final Uint8List? image;
  final Map<String, double> demoValues;

  TestRecord({
    required this.id,
    required this.capturedAt,
    required this.cycleDay,
    required this.isDemo,
    this.readerName,
    this.selectedChannel,
    this.image,
    Map<String, double> demoValues = const {},
  }) : demoValues = Map.unmodifiable(isDemo ? demoValues : <String, double>{});

  String get displayId {
    final parts = id
        .split('-')
        .where(
          (part) => !{
            'DEMO',
            'ILL',
            'ILLUSTRATIVE',
            'EXAMPLE',
          }.contains(part.toUpperCase()),
        );
    final suffix = parts.join('-');
    return suffix.startsWith('KVL-')
        ? suffix
        : 'KVL-${suffix.isEmpty ? capturedAt.microsecondsSinceEpoch.toRadixString(36).toUpperCase() : suffix}';
  }

  // Only calibrated measurements may populate clinical report result cells.
  // This prototype does not yet produce such measurements.
  String get resultValue => 'Not available';
  String get resultAvailability => 'Analysis pending';
  String get status => 'Analysis pending';
  String get summary => isDemo
      ? 'Hormone concentrations have not been measured for this record. Results remain unavailable until a reader test is analyzed.'
      : 'Your test images were received and a channel was selected. Hormone levels are not available because assay calibration has not been configured.';
  String get clinicianSummary =>
      'No calibrated hormone concentrations, validated reference intervals, or clinical interpretation are available for this record.';
  String get quality => isDemo
      ? 'No reader capture or assay quality assessment is attached to this record.'
      : 'Image selection completed. Control-line detection, specimen validity, and assay quality checks have not been evaluated.';

  Map<String, dynamic> toJson() => {
    'id': id,
    'capturedAt': capturedAt.toUtc().toIso8601String(),
    'cycleDay': cycleDay,
    'isDemo': isDemo,
    'readerName': readerName,
    'selectedChannel': selectedChannel,
    if (image != null) 'image': base64Encode(image!),
    'demoValues': demoValues,
  };

  factory TestRecord.fromJson(Map<String, dynamic> json) {
    final values = json['demoValues'];
    final cycleDay = json['cycleDay'];
    if (json['id'] is! String ||
        cycleDay is! int ||
        cycleDay < 1 ||
        json['isDemo'] is! bool ||
        json['capturedAt'] is! String) {
      throw const FormatException('Invalid test record');
    }
    return TestRecord(
      id: json['id'] as String,
      capturedAt: DateTime.parse(json['capturedAt'] as String),
      cycleDay: cycleDay,
      isDemo: json['isDemo'] as bool,
      readerName: json['readerName'] is String
          ? json['readerName'] as String
          : null,
      selectedChannel: json['selectedChannel'] is String
          ? json['selectedChannel'] as String
          : null,
      image: json['image'] is String
          ? base64Decode(json['image'] as String)
          : null,
      demoValues: values is Map
          ? {
              for (final entry in values.entries)
                if (hormones.contains(entry.key) &&
                    entry.value is num &&
                    (entry.value as num).isFinite)
                  entry.key.toString(): (entry.value as num).toDouble(),
            }
          : {},
    );
  }
}

String reportDate(DateTime date) {
  final local = date.toLocal();
  String two(int n) => n.toString().padLeft(2, '0');
  return '${two(local.day)}/${two(local.month)}/${local.year} ${two(local.hour)}:${two(local.minute)} (local time)';
}

